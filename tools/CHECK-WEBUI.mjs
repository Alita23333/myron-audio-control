import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('module-source/webroot/index.html'),app=read('module-source/webroot/app.js');
assert(!/<select\b/i.test(html),'Native select remains in HTML');
assert(!/createElement\(['"]select['"]\)/.test(app),'Native select remains in editor');
assert(!/\b(?:alert|confirm|prompt)\s*\(/.test(app),'Native JS dialog remains');
for(const mode of ['stock','default','per-app'])assert(html.includes(`name="mode" value="${mode}"`));
const sourceIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
assert.equal(new Set(sourceIds).size,sourceIds.length,'Duplicate DOM IDs');
for(const [,id] of app.matchAll(/\$\('([^']+)'\)/g))assert(sourceIds.includes(id),`Missing element: ${id}`);
assert(app.includes("if(forceFill||!dirty)"),'Refresh would replace dirty edits');
assert(app.includes("if(!loaded||busy||!dirty)return"),'Save guard missing');
assert(app.includes("bootMissing=state.bootReady!==true"),'Boot evidence guard missing');
const initLine=read('native/audioctl.cpp').split('\n').find(line=>line.includes('cmd=="init"'));
assert(initLine.includes('},"all")'),'Fresh installation default is not all');
assert(initLine.includes('!exists(root+"/runtime/pending")'),'Upgrade configuration preservation missing');
const version=read('module-source/module.prop').match(/^version=(.+)$/m)[1].trim();
assert(html.includes(`<span>${version}</span>`),'Displayed version mismatch');
console.log('PASS: native dialogs removed; fixed DOM/controls; dirty-edit preservation; boot evidence; new-install all; upgrade preservation; version alignment');
